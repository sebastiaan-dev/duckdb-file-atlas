/*
 * Scenarios: small, parameterised workloads that each show a storage effect,
 * plus TPC benchmarks and free-form SQL. Every scenario compiles to a SQL
 * script that the database builder runs in a fresh file.
 */

export type ScenarioId =
  | "tpch"
  | "tpcds"
  | "compression"
  | "churn"
  | "indexes"
  | "overflow"
  | "custom";

export interface ChoiceField {
  kind: "choice";
  key: string;
  label: string;
  options: { value: string; label: string }[];
}
export interface ToggleField {
  kind: "toggle";
  key: string;
  label: string;
}
export type ScenarioField = ChoiceField | ToggleField;

/** Setting values are strings ("1"/"0" for toggles) so links stay simple. */
export type ScenarioSettings = Record<string, string>;

export interface ScenarioDefinition {
  id: ScenarioId;
  name: string;
  /** One line under the tiles, describing what the scenario shows. */
  summary: string;
  fields: ScenarioField[];
  defaults: ScenarioSettings;
  sql: (settings: ScenarioSettings) => string;
  fileName: (settings: ScenarioSettings) => string;
}

const choice = (
  key: string,
  label: string,
  options: [string, string][],
): ChoiceField => ({
  kind: "choice",
  key,
  label,
  options: options.map(([value, text]) => ({ value, label: text })),
});
const toggle = (key: string, label: string): ToggleField => ({
  kind: "toggle",
  key,
  label,
});
const ROWS = (values: number[]) =>
  values.map((value): [string, string] => [
    String(value),
    value >= 1_000_000
      ? `${value / 1_000_000}M`
      : value >= 1000
        ? `${value / 1000}K`
        : String(value),
  ]);
const on = (value: string) => value === "1";
const lines = (...parts: (string | false)[]) =>
  `${parts.filter((part) => part !== false).join("\n")}\n`;

