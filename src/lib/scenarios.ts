export const scenario = (id: ScenarioId) =>
  SCENARIOS.find((item) => item.id === id)!;

/** The whole builder state; kept by the app and in shareable links. */
export interface ScenarioState {
  id: ScenarioId;
  /** Settings per scenario, so switching tiles keeps earlier choices. */
  settings: Record<ScenarioId, ScenarioSettings>;
  script: string;
  storageVersion: BuildStorageVersion;
  blockSize: BuildBlockSize;
  threads: BuildThreads;
}

export const DEFAULT_SCENARIO_STATE: ScenarioState = {
  id: "tpch",
  settings: Object.fromEntries(
    SCENARIOS.map((item) => [item.id, { ...item.defaults }]),
  ) as Record<ScenarioId, ScenarioSettings>,
  script: lines(
    "CREATE TABLE t AS SELECT i, i % 10 AS bucket FROM range(100000) t(i);",
  ),
  storageVersion: DEFAULT_STORAGE_VERSION,
  blockSize: DEFAULT_BLOCK_SIZE,
  threads: DEFAULT_THREADS,
};

/** Keep only allowed values; settings are interpolated into SQL. */
export function validSettings(
  definition: ScenarioDefinition,
  settings: Partial<ScenarioSettings> = {},
): ScenarioSettings {
  const valid = { ...definition.defaults };
  for (const field of definition.fields) {
    const value = settings[field.key];
    const allowed =
      field.kind === "toggle"
        ? ["0", "1"]
        : field.options.map((option) => option.value);
    if (value != null && allowed.includes(value)) valid[field.key] = value;
  }
  return valid;
}

/** The SQL a state runs: the custom script or the scenario's generated SQL. */
export function scenarioScript(state: ScenarioState) {
  if (state.id === "custom") return state.script;
  const definition = scenario(state.id);
  return definition.sql(validSettings(definition, state.settings[state.id]));
}

export function buildScenario(
  state: ScenarioState,
  options: { signal?: AbortSignal; onProgress?: (message: string) => void },
) {
  const statements = splitStatements(scenarioScript(state));
  if (!statements.length) throw new Error("The script has no statements.");
  const definition = scenario(state.id);
  return buildDatabase({
    ...options,
    fileName: definition.fileName(
      validSettings(definition, state.settings[state.id]),
    ),
    storageVersion: state.storageVersion,
    blockSize: state.blockSize,
    threads: state.threads,
    statements: statements.map(({ text, line }) => ({ sql: text, line })),
    timeoutMessage:
      "The build did not finish within five minutes. Try a smaller scenario.",
  });
}

export function buildError(error: unknown): string {
  const detail = error instanceof Error ? error.message : String(error);
  return `The database could not be built. The DuckDB runtime (about 35 MB) is served by this site; check your connection and retry. If memory is limited, choose a smaller scenario or close other tabs.${detail ? ` Details: ${detail}` : ""}`;
}

// --- Shareable links ------------------------------------------------------
// `#scenario=churn&rows=300000&…&storage=v2.0.0&block=262144&threads=1`; custom SQL is
// `#scenario=custom&sql=<deflate-raw, base64url>&…`.

const toBase64Url = (bytes: Uint8Array) =>
  btoa(String.fromCharCode(...bytes))
    .replaceAll("+", "-")
    .replaceAll("/", "_")
    .replace(/=+$/, "");
const fromBase64Url = (text: string) =>
  Uint8Array.from(
    atob(text.replaceAll("-", "+").replaceAll("_", "/")),
    (char) => char.charCodeAt(0),
  );
async function transform(bytes: Uint8Array, stream: GenericTransformStream) {
  const output = new Blob([bytes]).stream().pipeThrough(stream);
  return new Uint8Array(await new Response(output).arrayBuffer());
}

export async function encodeScenario(state: ScenarioState): Promise<string> {
  const params = new URLSearchParams({ scenario: state.id });
  if (state.id === "custom")
    params.set(
      "sql",
      toBase64Url(
        await transform(
          new TextEncoder().encode(state.script),
          new CompressionStream("deflate-raw"),
        ),
      ),
    );
  else
    for (const [key, value] of Object.entries(state.settings[state.id]))
      params.set(key, value);
  params.set("storage", state.storageVersion);
  params.set("block", String(state.blockSize));
  params.set("threads", String(state.threads));
  return params.toString();
}

/**
 * Parse a location hash. Every value is checked against the scenario's
 * fields, so links can never inject SQL; unknown values fall back to the
 * defaults. Returns null for hashes that are not scenario links.
 */
export async function decodeScenario(
  hash: string,
): Promise<ScenarioState | null> {
  const params = new URLSearchParams(hash.replace(/^#/, ""));
  // Links from before scenarios carry only `sql`.
  const id = (params.get("scenario") ??
    (params.has("sql") ? "custom" : null)) as ScenarioId | null;
  const definition = SCENARIOS.find((item) => item.id === id);
  if (!definition) return null;
  const state: ScenarioState = {
    ...DEFAULT_SCENARIO_STATE,
    id: definition.id,
    settings: { ...DEFAULT_SCENARIO_STATE.settings },
  };
  if (definition.id === "custom") {
    try {
      state.script = new TextDecoder().decode(
        await transform(
          fromBase64Url(params.get("sql") ?? ""),
          new DecompressionStream("deflate-raw"),
        ),
      );
    } catch {
      return null;
    }
  } else
    state.settings[definition.id] = validSettings(
      definition,
      Object.fromEntries(params),
    );
  const storage = params.get("storage") as BuildStorageVersion;
  const block = Number(params.get("block")) as BuildBlockSize;
  if (BUILD_STORAGE_VERSIONS.includes(storage)) state.storageVersion = storage;
  if (BUILD_BLOCK_SIZES.includes(block)) state.blockSize = block;
  const threads = BUILD_THREADS.find(
    (value) => String(value) === params.get("threads"),
  );
  if (threads != null) state.threads = threads;
  return state;
}
