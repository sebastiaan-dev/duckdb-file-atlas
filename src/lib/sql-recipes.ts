export const DEFAULT_SQL_RECIPE: SqlRecipe = {
  script: SQL_PRESETS[0].script,
  storageVersion: DEFAULT_STORAGE_VERSION,
  blockSize: DEFAULT_BLOCK_SIZE,
};

/** Name the file after the preset it came from, if unchanged. */
export function recipeFileName(recipe: SqlRecipe) {
  const preset = SQL_PRESETS.find((item) => item.script === recipe.script);
  return `${preset?.id ?? "custom-sql"}.duckdb`;
}

export function buildFromRecipe(
  recipe: SqlRecipe,
  options: { signal?: AbortSignal; onProgress?: (message: string) => void },
) {
  const statements = splitStatements(recipe.script);
  if (!statements.length) throw new Error("The script has no statements.");
  return buildDatabase({
    ...options,
    fileName: recipeFileName(recipe),
    storageVersion: recipe.storageVersion,
    blockSize: recipe.blockSize,
    statements: statements.map(({ text, line }) => ({ sql: text, line })),
    timeoutMessage: "The script did not finish within five minutes.",
  });
}

// --- Shareable links ------------------------------------------------------
// `#sql=<deflate-raw, base64url>&storage=v2.0.0&block=262144`

const toBase64Url = (bytes: Uint8Array) =>
  btoa(String.fromCharCode(...bytes))
    .replaceAll("+", "-")
    .replaceAll("/", "_")
    .replace(/=+$/, "");
const fromBase64Url = (text: string) =>
  Uint8Array.from(
    atob(text.replaceAll("-", "+").replaceAll("_", "/")),
    (char) => char.charCodeAt(0),
  );

async function transform(bytes: Uint8Array, stream: GenericTransformStream) {
  const output = new Blob([bytes]).stream().pipeThrough(stream);
  return new Uint8Array(await new Response(output).arrayBuffer());
}

export async function encodeRecipe(recipe: SqlRecipe): Promise<string> {
  const packed = await transform(
    new TextEncoder().encode(recipe.script),
    new CompressionStream("deflate-raw"),
  );
  return new URLSearchParams({
    sql: toBase64Url(packed),
    storage: recipe.storageVersion,
    block: String(recipe.blockSize),
  }).toString();
}

/** Parse a location hash; unknown or damaged links yield null. */
export async function decodeRecipe(hash: string): Promise<SqlRecipe | null> {
  const params = new URLSearchParams(hash.replace(/^#/, ""));
  const sql = params.get("sql");
  if (!sql) return null;
  try {
    const script = new TextDecoder().decode(
      await transform(
        fromBase64Url(sql),
        new DecompressionStream("deflate-raw"),
      ),
    );
    const storage = params.get("storage") as BuildStorageVersion;
    const block = Number(params.get("block")) as BuildBlockSize;
    return {
      script,
      storageVersion: BUILD_STORAGE_VERSIONS.includes(storage)
        ? storage
        : DEFAULT_STORAGE_VERSION,
      blockSize: BUILD_BLOCK_SIZES.includes(block) ? block : DEFAULT_BLOCK_SIZE,
    };
  } catch {
    return null;
  }
}
