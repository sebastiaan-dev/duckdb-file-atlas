/** Everything needed to rebuild the same database file. */
export interface SqlRecipe {
  script: string;
  storageVersion: BuildStorageVersion;
  blockSize: BuildBlockSize;
}

export interface SqlPreset {
  id: string;
  name: string;
  script: string;
}

