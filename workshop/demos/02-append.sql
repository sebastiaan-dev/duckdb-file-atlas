-- Ten modest 30,000-row transactions, not hundreds of thousands of INSERTs.
-- Checkpoint after each commit is intentional: this compares persistence
-- histories, NOT just CTAS syntax versus INSERT syntax or execution speed.
CREATE TABLE t (id BIGINT, value INTEGER, payload VARCHAR);
CREATE TEMP MACRO batch(lo, hi) AS TABLE
SELECT i AS id, (i % 1000)::INTEGER AS value, md5(i::VARCHAR) AS payload
FROM range(lo, hi) r(i) ORDER BY i;
BEGIN;
INSERT INTO t SELECT * FROM batch(0, 30000);
COMMIT;
CHECKPOINT;
BEGIN;
INSERT INTO t SELECT * FROM batch(30000, 60000);
COMMIT;
CHECKPOINT;
BEGIN;
INSERT INTO t SELECT * FROM batch(60000, 90000);
COMMIT;
CHECKPOINT;
BEGIN;
INSERT INTO t SELECT * FROM batch(90000, 120000);
COMMIT;
CHECKPOINT;
BEGIN;
INSERT INTO t SELECT * FROM batch(120000, 150000);
COMMIT;
CHECKPOINT;
BEGIN;
INSERT INTO t SELECT * FROM batch(150000, 180000);
COMMIT;
CHECKPOINT;
BEGIN;
INSERT INTO t SELECT * FROM batch(180000, 210000);
COMMIT;
CHECKPOINT;
BEGIN;
INSERT INTO t SELECT * FROM batch(210000, 240000);
COMMIT;
CHECKPOINT;
BEGIN;
INSERT INTO t SELECT * FROM batch(240000, 270000);
COMMIT;
CHECKPOINT;
BEGIN;
INSERT INTO t SELECT * FROM batch(270000, 300000);
COMMIT;
CHECKPOINT;
